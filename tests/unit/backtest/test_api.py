# Crash recovery startup hook
# ---------------------------------------------------------------------------


class TestCrashRecovery:
    @patch("app.modules.backtest.api.PostgresBacktestRepository")
    @patch("app.modules.backtest.api.async_session_factory")
    async def test_recover_stale_backtests_calls_mark_stale(self, mock_factory, mock_repo_cls):
        """recover_stale_backtests should create a session and call mark_stale_runs_failed."""
        from app.modules.backtest.api import recover_stale_backtests

        # session.begin() returns an async context manager
        mock_begin = MagicMock()
        mock_begin.__aenter__ = AsyncMock(return_value=None)
        mock_begin.__aexit__ = AsyncMock(return_value=False)

        mock_session = MagicMock()
        mock_session.begin.return_value = mock_begin

        # async_session_factory() returns an async context manager yielding the session
        mock_cm = MagicMock()
        mock_cm.__aenter__ = AsyncMock(return_value=mock_session)
        mock_cm.__aexit__ = AsyncMock(return_value=False)
        mock_factory.return_value = mock_cm

        mock_repo = AsyncMock()
        mock_repo.mark_stale_runs_failed = AsyncMock(return_value=3)
        mock_repo_cls.return_value = mock_repo

        count = await recover_stale_backtests()

        assert count == 3
        mock_repo.mark_stale_runs_failed.assert_called_once()

    @patch("app.modules.backtest.api.async_session_factory")
    async def test_recover_stale_backtests_returns_zero_on_db_error(self, mock_factory):
        """Should swallow DB errors and return 0 (best-effort)."""
        from app.modules.backtest.api import recover_stale_backtests

        mock_factory.side_effect = RuntimeError("DB down")

        count = await recover_stale_backtests()
        assert count == 0


