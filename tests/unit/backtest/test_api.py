class TestPostRun:
    @patch("app.modules.backtest.api._run_backtest_background", new_callable=AsyncMock)
    def test_returns_202_with_running_status(self, mock_bg, client):
        """POST /run returns 202 with status 'running' — engine runs in background."""
        response = client.post("/api/v1/backtest/run", json=_valid_config())
        assert response.status_code == 202
        data = response.json()
        assert data["status"] == "running"

    @patch("app.modules.backtest.api._run_backtest_background", new_callable=AsyncMock)
    def test_backtest_id_is_handler_generated_uuid(self, mock_bg, client):
        """backtest_id should be a UUID generated by the handler."""
        response = client.post("/api/v1/backtest/run", json=_valid_config())
        data = response.json()
        # Should be a valid UUID format (36 chars with dashes)
        assert len(data["backtest_id"]) == 36

    @patch("app.modules.backtest.api._run_backtest_background", new_callable=AsyncMock)
    def test_creates_run_record(self, mock_bg, client):
        """POST /run should create a BacktestRunRecord in _runs."""
        from app.modules.backtest.api import _runs
        response = client.post("/api/v1/backtest/run", json=_valid_config())
        backtest_id = response.json()["backtest_id"]
        assert backtest_id in _runs
        assert _runs[backtest_id].status == "running"

    @patch("app.modules.backtest.api._run_backtest_background", new_callable=AsyncMock)
    def test_enqueues_background_task(self, mock_bg, client):
        """POST /run should enqueue _run_backtest_background via BackgroundTasks."""
        response = client.post("/api/v1/backtest/run", json=_valid_config())
        backtest_id = response.json()["backtest_id"]
        mock_bg.assert_called_once()
        assert mock_bg.call_args[0][0] == backtest_id

    def test_invalid_config_returns_422(self, client):
        """Missing required fields should return validation error."""
        response = client.post("/api/v1/backtest/run", json={"start_date": "2024-01-02"})
        assert response.status_code == 422


