class TestBackgroundPersistence:
    @patch("app.modules.backtest.api._persist_result", new_callable=AsyncMock)
    @patch("app.modules.backtest.context.BacktestContext.build", new_callable=AsyncMock)
    async def test_persists_result_on_success(self, mock_build, mock_persist):
        """_run_backtest_background should persist result to DB on success."""
        from app.modules.backtest.api import (
            BacktestRunRecord,
            _run_backtest_background,
            _runs,
        )
        from app.modules.backtest.config import BacktestConfig

        mock_ctx = MagicMock()
        mock_ctx.cancelled = asyncio.Event()
        mock_ctx.trading_days = []
        mock_ctx.rebalance_days = set()
        mock_ctx.trade_repo = None
        mock_ctx.effective_agents_config = None
        mock_build.return_value = mock_ctx

        config = BacktestConfig(
            start_date="2024-01-02",
            end_date="2024-06-28",
            initial_capital=1_000_000,
            rebalance_frequency="weekly",
            branch_name="growth",
            use_llm_agents=False,
        )
        _runs["test-1"] = BacktestRunRecord(
            backtest_id="test-1", status="running", config=config
        )

        await _run_backtest_background("test-1", config)

        mock_persist.assert_called_once()
        assert _runs["test-1"].status == "completed"

    @patch("app.modules.backtest.api._persist_result", new_callable=AsyncMock)
    @patch("app.modules.backtest.context.BacktestContext.build", new_callable=AsyncMock)
    async def test_still_succeeds_if_persistence_fails(self, mock_build, mock_persist):
        """In-memory record should be valid even if DB persistence fails."""
        from app.modules.backtest.api import (
            BacktestRunRecord,
            _run_backtest_background,
            _runs,
        )
        from app.modules.backtest.config import BacktestConfig

        mock_ctx = MagicMock()
        mock_ctx.cancelled = asyncio.Event()
        mock_ctx.trading_days = []
        mock_ctx.rebalance_days = set()
        mock_ctx.trade_repo = None
        mock_ctx.effective_agents_config = None
        mock_build.return_value = mock_ctx
        mock_persist.side_effect = RuntimeError("DB connection lost")

        config = BacktestConfig(
            start_date="2024-01-02",
            end_date="2024-06-28",
            initial_capital=1_000_000,
            rebalance_frequency="weekly",
            branch_name="growth",
            use_llm_agents=False,
        )
        _runs["test-2"] = BacktestRunRecord(
            backtest_id="test-2", status="running", config=config
        )

        await _run_backtest_background("test-2", config)

        # In-memory record should still be valid despite DB failure
        assert _runs["test-2"].status == "completed"
        assert _runs["test-2"].result is not None


